"""PlatformIO pre-build script: gzip web/index.html into src/web/index_html.h.

The web UI is compiled into the firmware, so no separate filesystem upload is needed.
The header is only rewritten when its content changes.
"""
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
src = os.path.join(project_dir, "web", "index.html")
dst = os.path.join(project_dir, "src", "web", "index_html.h")

if os.path.exists(src):
    with open(src, "rb") as f:
        raw = f.read()
else:
    raw = b"<!doctype html><title>HA Panel</title><p>web/index.html missing at build time.</p>"

data = gzip.compress(raw, compresslevel=9, mtime=0)
lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")

header = (
    "// GENERATED by tools/embed_web.py from web/index.html - do not edit.\n"
    "#pragma once\n"
    "#include <stddef.h>\n"
    "#include <stdint.h>\n\n"
    "static const size_t INDEX_HTML_GZ_LEN = %d;\n"
    "static const uint8_t INDEX_HTML_GZ[] = {\n%s\n};\n" % (len(data), "\n".join(lines))
)

os.makedirs(os.path.dirname(dst), exist_ok=True)
old = None
if os.path.exists(dst):
    with open(dst, "r") as f:
        old = f.read()
if old != header:
    with open(dst, "w") as f:
        f.write(header)
    print("embed_web: %s -> %s (%d bytes raw, %d gz)" % (src, dst, len(raw), len(data)))
